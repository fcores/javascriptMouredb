// VAR - Forma Original para declarar variables - NO SE USA - EXISTEN DE FORMA GLOBAL

var helloWorld = "Hola JS"
console.log(helloWorld)

helloWorld = "Hola de nuevo JS"
console.log(helloWorld)


// LET - SOLO SE PUEDE EJECUTAR EN EL AMBITO DE EJECUCION
let helloWorld2 = "Hola JS 2"
console.log(helloWorld2)

helloWorld2 = "Hola de nuevo JS 2"
console.log(helloWorld2)

// CONST - NO PERMITE MODIFICARLA SOLO SE USA PARA CONSTANTES CON EL MISMO AMBITO DE EJECUCION
const helloWorld3 = "Hola JS 3"
console.log(helloWorld3)

